/** Selector + `color-scheme` for each palette, in the order the CSS emits them. */
const THEME_RULES: { name: keyof typeof THEME_PALETTES; selector: string; scheme: "dark" | "light" }[] = [
  { name: "dark", selector: ':root,\n[data-theme="dark"]', scheme: "dark" },
  { name: "light", selector: '[data-theme="light"]', scheme: "light" },
  { name: "green", selector: '[data-theme="green"]', scheme: "dark" },
  { name: "blue", selector: '[data-theme="blue"]', scheme: "dark" },
  { name: "red", selector: '[data-theme="red"]', scheme: "dark" },
];

/**
 * The full contents of `src/app/styles/tokens.css` — every theme's custom-prop
 * block, derived from THEME_PALETTES. `scripts/gen-tokens.mjs` writes this to
 * disk at prebuild; `tokens.test.ts` fails if the committed file drifts from it.
 * This is the single source of truth for theme colour: globals.css must never
 * redeclare a `[data-theme]` block.
 */
export function tokensCssFile(): string {
  const blocks = THEME_RULES.map(({ name, selector, scheme }) => {
    const decls = Object.entries(cssVars(THEME_PALETTES[name]))
      .map(([prop, value]) => `    ${prop}: ${value};`)
      .join("\n");
    const indentedSelector = selector
      .split("\n")
      .map((line) => `  ${line}`)
      .join("\n");
    return `${indentedSelector} {\n${decls}\n    color-scheme: ${scheme};\n  }`;
  });
  return [
    "/* GENERATED by scripts/gen-tokens.mjs from src/lib/themePalettes.ts — do not edit. */",
    "@layer tokens {",
    blocks.join("\n\n"),
    "}",
    "",
  ].join("\n");
}
