export type ThemePalette = {
  bg: string;
  bg2: string;
  surface: string;
  line: string;
  fg: string;
  fgDim: string;
  muted: string;
  accent: string;
  accentFg: string;
  signal: string;
  danger: string;
  dangerFg: string;
  spot: string;
  glow: string;
};

export function cssVars(palette: ThemePalette): Record<string, string> {
  return {
    "--ink": palette.bg,
    "--bg2": palette.bg2,
    "--panel": palette.surface,
    "--line": palette.line,
    "--paper": palette.fg,
    "--paper-dim": palette.fgDim,
    "--muted": palette.muted,
    "--brass": palette.accent,
    "--brass-ink": palette.accentFg,
    "--signal": palette.signal,
    "--danger": palette.danger,
    "--spot": palette.spot,
    "--glow": palette.glow,
  };
}

